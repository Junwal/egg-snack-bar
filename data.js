/* 초반 5판은 표로 못박는다. base 공식만 쓰면 floor(st/6) 이 0으로 눌려서
   S1·S2·S3 이 전부 '멸치 3개'로 같아진다 — 판을 바꿀 이유가 사라진다 */
const EARLY_QTY = [null, [3,3], [3,4], [4,6], [4,6], [5,7]];   // S1 은 첫 메뉴 재료를 한 판에 정확히 채워 준다
function stageLoot(st){
  const lines = huntLines(st), g = gradeOf(st), t = gradeT(st);
  const base = 3 + Math.floor(st/6);
  const out = [];
  for(const k of lines){
    if(g>0){
      out.push({ k, g,     min: Math.floor(t*2),      max: 1 + Math.round(t*4) });
      out.push({ k, g:g-1, min: Math.max(1, base-1),  max: base + 1 });
    } else {
      const e = EARLY_QTY[st];
      out.push({ k, g:0,   min: e?e[0]:base,          max: e?e[1]:base + Math.floor(st/4) });
    }
  }
  return out.sort((a,b)=> b.g-a.g || LK.indexOf(a.k)-LK.indexOf(b.k));
}
const lootTotal = st => stageLoot(st).reduce((a,x)=>a+(x.min+x.max)/2, 0);
